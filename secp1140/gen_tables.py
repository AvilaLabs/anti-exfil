#!/usr/bin/env python3
"""Write anti_exfil_vectors.h from ../vectors/bip-anti-exfil.json and
../vectors/bip-anti-exfil-boundary.json.

The header holds the valid and rejection tables of both schemes as C89 static
const data; the boundary file adds key-range failures and host-accept tuples. Messages are byte arrays (one is 1024 bytes, longer than a C89
string literal may be); every other field is a lowercase hex string, left
as written in the vector file, so wrong lengths stay visible. Forced-hash
cases need a hash override, so only their ids and expected outcomes are kept.

Usage: gen_tables.py          write the header
       gen_tables.py --check  exit 1 if the header is not what the vector file gives"""
import hashlib, json, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
VECTORS = HERE.parent / "vectors" / "bip-anti-exfil.json"
BOUNDARY = HERE.parent / "vectors" / "bip-anti-exfil-boundary.json"
HEADER = HERE / "anti_exfil_vectors.h"


def render(raw, braw):
    d = json.loads(raw)
    bd = json.loads(braw)
    out = ["/* Generated by gen_tables.py from vectors/bip-anti-exfil.json, sha256 %s," % hashlib.sha256(raw).hexdigest(),
           " * and vectors/bip-anti-exfil-boundary.json, sha256 %s." % hashlib.sha256(braw).hexdigest(),
           " * Do not edit; gen_tables.py --check tells whether it is current. */",
           "#ifndef ANTI_EXFIL_VECTORS_H", "#define ANTI_EXFIL_VECTORS_H", "",
           '#define AE_VECTORS_SHA256 "%s"' % hashlib.sha256(raw).hexdigest(),
           '#define AE_BOUNDARY_SHA256 "%s"' % hashlib.sha256(braw).hexdigest(), "",
           "typedef struct {",
           "    const char *id, *sk, *rho, *pk, *hc, *r0, *sig;",
           "    const unsigned char *m; size_t mlen;",
           "    int w_odd;",
           "} ae_valid;",
           "typedef struct {",
           "    const char *id, *defect, *from, *pk, *rho, *r0, *sig;",
           "    const unsigned char *m; size_t mlen;",
           "} ae_reject;",
           "typedef struct { const char *id, *expected; } ae_forced;",
           "typedef struct {",
           "    const char *id, *sk, *rho, *hc;",
           "    const unsigned char *m; size_t mlen;",
           "} ae_devfail;", ""]

    def marr(name, hexs):
        b = bytes.fromhex(hexs)
        if not b:
            out.append("static const unsigned char %s[1] = {0};" % name)
            return
        rows = [", ".join("0x%02x" % x for x in b[i:i + 12]) for i in range(0, len(b), 12)]
        out.append("static const unsigned char %s[%d] = {\n    %s\n};" % (name, len(b), ",\n    ".join(rows)))

    q = lambda s: '"%s"' % s
    for doc, pre in ((d, "ae_"), (bd, "ae_b_")):
        for key, nm in (("bip340", "schnorr"), ("ecdsa", "ecdsa")):
            sec = doc[key]
            tag = "%s%s" % (pre, nm)
            for i, c in enumerate(sec["valid"]):
                marr("%s_vm%d" % (tag, i), c["m"])
            for i, c in enumerate(sec["reject"]):
                marr("%s_rm%d" % (tag, i), c["m"])
            for i, c in enumerate(sec.get("device_fail", [])):
                marr("%s_dm%d" % (tag, i), c["m"])
            for i, c in enumerate(sec.get("host_accept", [])):
                marr("%s_am%d" % (tag, i), c["m"])
            out.append("")
            out.append("static const ae_valid %s_valid[] = {" % tag)
            for i, c in enumerate(sec["valid"]):
                out.append("    {%s, %s, %s, %s, %s, %s, %s, %s_vm%d, %d, %d}," % (
                    q(c["id"]), q(c["sk"]), q(c["rho"]), q(c["pk"]), q(c["hc"]), q(c["R0_bytes"]), q(c["sig"]),
                    tag, i, len(c["m"]) // 2, 1 if c["W_parity"] == "odd" else 0))
            out.append("};")
            out.append("static const ae_reject %s_reject[] = {" % tag)
            for i, c in enumerate(sec["reject"]):
                out.append("    {%s, %s, %s, %s, %s, %s, %s, %s_rm%d, %d}," % (
                    q(c["id"]), q(c["defect"]), q(c.get("derived_from", "")), q(c["pk"]), q(c["rho"]), q(c["R0_bytes"]), q(c["sig"]),
                    tag, i, len(c["m"]) // 2))
            out.append("};")
            if pre == "ae_":
                out.append("static const ae_forced %s_forced[] = {" % tag)
                for c in sec["forced_hash"]:
                    out.append("    {%s, %s}," % (q(c["id"]), q(c["expected"])))
                out.append("};")
            else:
                out.append("static const ae_devfail %s_devfail[] = {" % tag)
                for i, c in enumerate(sec["device_fail"]):
                    out.append("    {%s, %s, %s, %s, %s_dm%d, %d}," % (q(c["id"]), q(c["sk"]), q(c["rho"]), q(c["hc"]), tag, i, len(c["m"]) // 2))
                out.append("};")
                # Host-accept tuples use the rejection layout; defect is "accept" and there is no source case.
                hl = sec.get("host_accept", [])
                if hl:
                    out.append("static const ae_reject %s_hostok[%d] = {" % (tag, len(hl)))
                for i, c in enumerate(hl):
                    out.append("    {%s, \"accept\", \"\", %s, %s, %s, %s, %s_am%d, %d}," % (
                        q(c["id"]), q(c["pk"]), q(c["rho"]), q(c["R0_bytes"]), q(c["sig"]), tag, i, len(c["m"]) // 2))
                if hl:
                    out.append("};")
                out.append("#define %s_NHOSTOK %d" % (tag.upper(), len(hl)))
            out.append("")
    out += ["#endif", ""]
    return "\n".join(out)


def main():
    raw = VECTORS.read_bytes()
    braw = BOUNDARY.read_bytes()
    text = render(raw, braw)
    if "--check" in sys.argv[1:]:
        if not HEADER.exists() or HEADER.read_text() != text:
            print("anti_exfil_vectors.h is out of date for the vector files (sha256 %s, boundary %s); run gen_tables.py" % (hashlib.sha256(raw).hexdigest(), hashlib.sha256(braw).hexdigest()))
            return 1
        print("anti_exfil_vectors.h is current (vector files sha256 %s, boundary %s)" % (hashlib.sha256(raw).hexdigest(), hashlib.sha256(braw).hexdigest()))
        return 0
    HEADER.write_text(text)
    print("wrote %s (vector files sha256 %s, boundary %s)" % (HEADER.name, hashlib.sha256(raw).hexdigest(), hashlib.sha256(braw).hexdigest()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
